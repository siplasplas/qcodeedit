#!/usr/bin/env python3
"""Generates spell/src/KeyboardLayouts.inc from the X keyboard layouts (xkb).

For each layout: the base letters of the three letter rows (for neighbouring
keys and hands), and every other character of a letter key (Shift, AltGr,
Shift+AltGr; not ASCII) with the key's base letter, so
that a character typed with AltGr held ("©" for "r" on the Polish keyboard)
is known as that key.

Usage: tools/gen_keyboard_layouts.py > spell/src/KeyboardLayouts.inc
Reads /usr/share/X11/xkb/symbols and /usr/include/X11/keysymdef.h.
"""

import re
import sys

SYMBOLS = "/usr/share/X11/xkb/symbols"
KEYSYMDEF = "/usr/include/X11/keysymdef.h"
# (name in the program, xkb file, xkb variant or None for the default one)
LAYOUTS = [
    ("pl", "pl", "basic"),
    ("us", "us", "basic"),
    ("de", "de", "basic"),
    ("fr", "fr", "basic"),
    ("es", "es", "basic"),
]
ROWS = [
    [f"AD{i:02d}" for i in range(1, 13)],
    [f"AC{i:02d}" for i in range(1, 12)],
    [f"AB{i:02d}" for i in range(1, 11)],
]


def keysym_chars():
    chars = {}
    pattern = re.compile(r"#define XK_(\w+)\s+0x[0-9a-fA-F]+\s*/\*\s*\(?U\+([0-9A-Fa-f]{4,6})")
    with open(KEYSYMDEF, encoding="utf-8") as header:
        for line in header:
            match = pattern.match(line)
            if match:
                chars.setdefault(match.group(1), chr(int(match.group(2), 16)))
    return chars


KEYSYMS = keysym_chars()


def to_char(name):
    if name in KEYSYMS:
        return KEYSYMS[name]
    if re.fullmatch(r"U[0-9A-Fa-f]{4,6}", name):
        return chr(int(name[1:], 16))
    return None  # dead keys, NoSymbol, ...


def section(file, variant):
    with open(f"{SYMBOLS}/{file}", encoding="utf-8") as f:
        text = f.read()
    blocks = list(re.finditer(r'((?:\w+\s+)*)xkb_symbols\s+"([^"]+)"\s*\{(.*?)\n\};', text, re.S))
    for block in blocks:
        if variant is None and "default" in block.group(1).split():
            return block.group(3)
        if block.group(2) == variant:
            return block.group(3)
    if variant is None and blocks:
        return blocks[0].group(3)
    raise SystemExit(f"no variant {variant} in {file}")


def keys_of(file, variant):
    """Key name -> list of characters by level, with includes applied first."""
    keys = {}
    body = section(file, variant)
    for line in body.splitlines():
        line = line.split("//")[0]
        include = re.search(r'include\s+"([^"(]+)(?:\(([^)]+)\))?"', line)
        if include:
            keys.update(keys_of(include.group(1), include.group(2)))
            continue
        key = re.search(r"key\s+<(\w+)>\s*\{[^\[]*\[([^\]]*)\]", line)
        if key:
            names = [n.strip() for n in key.group(2).split(",")]
            keys[key.group(1)] = [to_char(n) for n in names]
    return keys


# Layouts not in xkb, written here: (name, rows, pairs).
MANUAL = [
    # Windows "Polish (Programmers)": AltGr gives only the Polish letters
    # (and € on u); on the other keys it gives nothing.
    ("pl-windows", ["qwertyuiop[]", "asdfghjkl;'", "zxcvbnm,./"],
     "ąaĄaćcĆcęeĘełlŁlńnŃnóoÓośsŚsźxŹxżzŻz"),
]


def cxx(text):
    return 'u"' + "".join(c if c not in '"\\' else "\\" + c for c in text) + '"'


def main():
    out = ["// Generated by tools/gen_keyboard_layouts.py from the X keyboard layouts;",
           "// do not edit. For each layout: the base characters of the letter rows,",
           "// and pairs (character, base letter of its key) for the other levels.",
           "", "const KeyboardLayoutData kKeyboardLayouts[] = {"]
    for name, file, variant in LAYOUTS:
        keys = keys_of(file, variant)
        rows = []
        for row in ROWS:
            rows.append("".join((keys.get(k) or [None])[0] or " " for k in row))
        pairs = []
        for row in ROWS:
            for k in row:
                levels = keys.get(k) or []
                if not levels or not levels[0] or not levels[0].isalpha():
                    continue
                base = levels[0]
                for c in levels[1:4]:
                    # Not ASCII: Shift's own symbols never stand for a letter.
                    # Punctuation (quotes: „ on v, ” on b of the Polish
                    # keyboard) is kept too: after a letter with AltGr it is
                    # AltGr not let go ("zró”" for zrób).
                    if not c or ord(c) < 0x80:
                        continue
                    if c.lower() != base and c not in pairs[0::2]:
                        pairs += [c, base]
        out.append(f'    {{"{name}", {{{cxx(rows[0])}, {cxx(rows[1])}, {cxx(rows[2])}}},')
        out.append(f"     {cxx(''.join(pairs))}}},")
    for name, rows, pairs in MANUAL:
        out.append(f'    {{"{name}", {{{cxx(rows[0])}, {cxx(rows[1])}, {cxx(rows[2])}}},')
        out.append(f"     {cxx(pairs)}}},")
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
